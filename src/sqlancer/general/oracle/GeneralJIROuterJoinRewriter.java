package sqlancer.general.oracle;

import java.util.ArrayList;
import java.util.List;

import sqlancer.common.ast.newast.ColumnReferenceNode;
import sqlancer.common.ast.newast.NewBinaryOperatorNode;
import sqlancer.common.ast.newast.Node;
import sqlancer.common.ast.newast.TableReferenceNode;
import sqlancer.general.GeneralSchema.GeneralColumn;
import sqlancer.general.GeneralToStringVisitor;
import sqlancer.general.ast.GeneralBinaryLogicalOperator;
import sqlancer.general.ast.GeneralConstant;
import sqlancer.general.ast.GeneralExists;
import sqlancer.general.ast.GeneralExpression;
import sqlancer.general.ast.GeneralJoin;
import sqlancer.general.ast.GeneralJoin.JoinType;
import sqlancer.general.ast.GeneralSelect;

/** Complete RIGHT/FULL decompositions for the plain SELECTs generated by JIR. */
final class GeneralJIROuterJoinRewriter {
    private GeneralJIROuterJoinRewriter() {
    }

    static List<String> rewriteFull(GeneralSelect original, int joinIndex) {
        GeneralJoin join = (GeneralJoin) original.getJoinList().get(joinIndex);
        if (join.getJoinType() != JoinType.FULL) {
            throw new IllegalArgumentException("Expected FULL JOIN");
        }
        List<String> branches = new ArrayList<>();
        branches.add(variant(original, joinIndex, join.withJoinType(JoinType.INNER, null), null));
        branches.add(unmatched(original, joinIndex, join, true));
        branches.add(unmatched(original, joinIndex, join, false));
        return branches;
    }

    static List<String> rewriteRight(GeneralSelect original, int joinIndex, boolean nativeAnti) {
        GeneralJoin join = (GeneralJoin) original.getJoinList().get(joinIndex);
        if (join.getJoinType() != JoinType.RIGHT || original.getWhereClause() != null) {
            throw new IllegalArgumentException("RIGHT decomposition requires the unfiltered JIR query");
        }
        List<Node<GeneralExpression>> projection = new ArrayList<>();
        for (Node<GeneralExpression> expression : original.getFetchColumns()) {
            if (!(expression instanceof ColumnReferenceNode<?, ?>)) {
                throw new IllegalArgumentException("RIGHT decomposition requires column projections");
            }
            GeneralColumn column = (GeneralColumn) ((ColumnReferenceNode<?, ?>) expression).getColumn();
            projection.add(column.getTable().getName().equals(join.getLeftTable().getTable().getName())
                    ? GeneralConstant.createNullConstant() : expression);
        }
        Node<GeneralExpression> input;
        Node<GeneralExpression> filter = null;
        if (nativeAnti) {
            input = new ReversedAntiJoin(join);
        } else {
            input = join.getRightTable();
            GeneralSelect probe = new GeneralSelect();
            probe.setFetchColumns(List.of(GeneralConstant.createIntConstant(1)));
            probe.setFromList(List.of(join.getLeftTable()));
            probe.setWhereClause(join.getOnCondition());
            filter = new GeneralExists(probe, true);
        }
        GeneralSelect unmatched = variantSelect(original, joinIndex, input, filter);
        unmatched.setFetchColumns(projection);
        return List.of(variant(original, joinIndex, join.withJoinType(JoinType.INNER, null), null),
                asString(unmatched));
    }

    // GeneralJoin only accepts a base table on its left. This JIR-only node also allows the
    // original right derived input to become the left operand of the reversed ANTI JOIN.
    private static final class ReversedAntiJoin implements Node<GeneralExpression> {
        private final GeneralJoin original;

        private ReversedAntiJoin(GeneralJoin original) {
            this.original = original;
        }
    }

    private static String unmatched(GeneralSelect original, int index, GeneralJoin join, boolean preserveLeft) {
        GeneralSelect probe = new GeneralSelect();
        probe.setFetchColumns(List.of(GeneralConstant.createIntConstant(1)));
        // The inner relation shadows only the NULL-extended side. The preserved side remains correlated.
        probe.setFromList(List.of(preserveLeft ? join.getRightTable() : join.getLeftTable()));
        probe.setWhereClause(join.getOnCondition());
        // Reuse the FULL JOIN's ON condition for the NULL-extending branch. The NOT EXISTS filter below removes
        // preserved-side rows that have a real match, so the branch emits exactly the unmatched rows while keeping
        // the same join predicate as the original FULL JOIN.
        GeneralJoin padding = join.withJoinType(preserveLeft ? JoinType.LEFT : JoinType.RIGHT, null)
                .withOnCondition(join.getOnCondition());
        return variant(original, index, padding, new GeneralExists(probe, true));
    }

    private static String variant(GeneralSelect original, int index, GeneralJoin replacement,
            Node<GeneralExpression> filter) {
        return asString(variantSelect(original, index, replacement, filter));
    }

    private static GeneralSelect variantSelect(GeneralSelect original, int index, Node<GeneralExpression> replacement,
            Node<GeneralExpression> filter) {
        GeneralSelect variant = new GeneralSelect();
        variant.setFetchColumns(original.getFetchColumns());
        variant.setFromList(original.getFromList());
        List<Node<GeneralExpression>> joins = new ArrayList<>(original.getJoinList());
        joins.set(index, replacement);
        variant.setJoinList(joins);
        Node<GeneralExpression> where = original.getWhereClause();
        if (filter != null) {
            where = where == null ? filter
                    : new NewBinaryOperatorNode<>(where, filter, GeneralBinaryLogicalOperator.AND);
        }
        variant.setWhereClause(where);
        return variant;
    }

    static String asString(GeneralSelect select) {
        GeneralToStringVisitor visitor = new GeneralToStringVisitor() {
            @Override
            public void visitSpecific(Node<GeneralExpression> node) {
                // Isolate comma-separated JOIN inputs consistently in both the original and all branches.
                // Otherwise SQLite may treat preceding FROM items as part of an outer join's left operand.
                if (node instanceof ReversedAntiJoin) {
                    GeneralJoin join = ((ReversedAntiJoin) node).original;
                    sb.append("(");
                    visit(join.getRightTable());
                    if (join.getRightTable() instanceof TableReferenceNode<?, ?>) {
                        // Keep ANTI from being interpreted as a table alias by unsupported dialects.
                        sb.append(" AS ");
                        sb.append(((TableReferenceNode<?, ?>) join.getRightTable()).getTable().getName());
                    }
                    sb.append(" ANTI JOIN ");
                    visit(join.getLeftTable());
                    sb.append(" ON ");
                    visit(join.getOnCondition());
                    sb.append(")");
                } else if (node instanceof GeneralJoin) {
                    sb.append("(");
                    super.visitSpecific(node);
                    sb.append(")");
                } else {
                    super.visitSpecific(node);
                }
            }
        };
        visitor.visit(select);
        return visitor.get();
    }
}
